import { api } from './client'
import { USE_MOCKS } from './config'
import { mockReport } from './mocks/reports'
import { saveBlob } from '../lib/download'
import { toApiParams } from '../lib/reports'
import type { ReportFilters, ReportFormat } from '../lib/reports'
import { normalizeReport, toCsv } from '../lib/reportTable'
import type { ReportTable } from '../lib/reportTable'

const delay = (ms: number) => new Promise((r) => setTimeout(r, ms))

// GET /reports/{type}?format=json  -> preview table
export async function getReport(f: ReportFilters): Promise<ReportTable> {
  if (USE_MOCKS) {
    await delay(250)
    return mockReport(f)
  }
  const res = await api.get<unknown>(`/reports/${f.type}`, { params: toApiParams(f, 'json') })
  return normalizeReport(res.data)
}

// GET /reports/{type}?format=csv|json|pdf  -> file (fetched with the auth header, then saved)
export async function downloadReport(f: ReportFilters, format: ReportFormat): Promise<void> {
  const name = `report-${f.type}-${new Date().toISOString().slice(0, 10)}.${format}`
  if (USE_MOCKS) {
    await delay(150)
    const t = mockReport(f)
    if (format === 'csv') saveBlob(new Blob([toCsv(t)], { type: 'text/csv' }), name)
    else if (format === 'json') saveBlob(new Blob([JSON.stringify(t, null, 2)], { type: 'application/json' }), name)
    else throw new Error('PDF export is generated by the backend and is not available with mock data.')
    return
  }
  const res = await api.get<Blob>(`/reports/${f.type}`, { params: toApiParams(f, format), responseType: 'blob' })
  saveBlob(res.data, name)
}
